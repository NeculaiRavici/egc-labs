void Lab3::Init()
{
    glm::ivec2 resolution = window->GetResolution();
    auto camera = GetSceneCamera();
    camera->SetOrthographic(0, (float)resolution.x, 0, (float)resolution.y, 0.01f, 400);
    camera->SetPosition(glm::vec3(0, 0, 50));
    camera->SetRotation(glm::vec3(0, 0, 0));
    camera->Update();
    GetCameraInput()->SetActive(false);

    glm::vec3 corner = glm::vec3(0, 0, 0);
    float squareSide = 100;

    // The square's center, needed to rotate / scale it around itself
    // instead of around its bottom-left corner (the origin)
    cx = corner.x + squareSide / 2;
    cy = corner.y + squareSide / 2;

    // Initialize tx and ty (the translation steps)
    translateX = 0;
    translateY = 0;

    // Initialize sx and sy (the scale factors)
    scaleX = 1;
    scaleY = 1;

    // Initialize angularStep
    angularStep = 0;

    translateDir = 1;
    scaleDir = 1;

    Mesh* square1 = object2D::CreateSquare("square1", corner, squareSide, glm::vec3(1, 0, 0), true);
    AddMeshToList(square1);

    Mesh* square2 = object2D::CreateSquare("square2", corner, squareSide, glm::vec3(0, 1, 0));
    AddMeshToList(square2);

    Mesh* square3 = object2D::CreateSquare("square3", corner, squareSide, glm::vec3(0, 0, 1));
    AddMeshToList(square3);
}


void Lab3::FrameStart()
{
    // Clears the color buffer (using the previously set color) and depth buffer
    glClearColor(0, 0, 0, 1);
    glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT);

    glm::ivec2 resolution = window->GetResolution();
    // Sets the screen area where to draw
    glViewport(0, 0, resolution.x, resolution.y);
}


void Lab3::Update(float deltaTimeSeconds)
{
    // Translation: move up and down between 0 and 200 pixels
    translateY += translateDir * 150 * deltaTimeSeconds;
    if (translateY > 200) {
        translateY = 200;
        translateDir = -1;
    } else if (translateY < 0) {
        translateY = 0;
        translateDir = 1;
    }

    // Rotation: one full turn every ~2 seconds
    angularStep += glm::pi<float>() * deltaTimeSeconds;

    // Scale: pulse between 0.5 and 1.5
    scaleX += scaleDir * deltaTimeSeconds;
    if (scaleX > 1.5f) {
        scaleX = 1.5f;
        scaleDir = -1;
    } else if (scaleX < 0.5f) {
        scaleX = 0.5f;
        scaleDir = 1;
    }
    scaleY = scaleX;

    modelMatrix = glm::mat3(1);
    modelMatrix *= transform2D::Translate(150, 250);
    modelMatrix *= transform2D::Translate(translateX, translateY);

    RenderMesh2D(meshes["square1"], shaders["VertexColor"], modelMatrix);

    modelMatrix = glm::mat3(1);
    modelMatrix *= transform2D::Translate(400, 250);
    // Rotate around the square's own center: move the center to the
    // origin, rotate, then move it back
    modelMatrix *= transform2D::Translate(cx, cy);
    modelMatrix *= transform2D::Rotate(angularStep);
    modelMatrix *= transform2D::Translate(-cx, -cy);

    RenderMesh2D(meshes["square2"], shaders["VertexColor"], modelMatrix);

    modelMatrix = glm::mat3(1);
    modelMatrix *= transform2D::Translate(650, 250);
    // Scale around the square's own center
    modelMatrix *= transform2D::Translate(cx, cy);
    modelMatrix *= transform2D::Scale(scaleX, scaleY);
    modelMatrix *= transform2D::Translate(-cx, -cy);

    RenderMesh2D(meshes["square3"], shaders["VertexColor"], modelMatrix);
}


